#!/usr/bin/env node
/**
 * Mirror canonical source fileId pins from governance/source-registry.json into each agent
 * wrapper, inside a generated block.
 *
 * Why this exists (IF-2026-09-01-018, second remediation): agent wrappers instruct fileId-first
 * retrieval, but the registry is a repo file. When the runtime does not expose a filesystem read
 * tool to subagents, the agent cannot open it and degrades to resolving canonical sources BY TITLE
 * — which CLAUDE.md 4.1 forbids and which live regression on 2026-09-01 confirmed happening.
 *
 * A fileId is a POINTER, not canonical content, so mirroring one into a wrapper does not violate
 * the no-cached-Drive-content rule (CLAUDE.md 4.8 / T-02 / T-22). The registry remains the single
 * source of truth; this only copies pointers, and T-34 fails the build if a copy ever drifts.
 *
 *   node scripts/sync-source-pins.js          # rewrite the generated blocks
 *   node scripts/sync-source-pins.js --check  # exit 1 if any block is stale
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const START = '<!-- SOURCE-PINS:START — generated by scripts/sync-source-pins.js — do not edit by hand -->';
const END = '<!-- SOURCE-PINS:END -->';

function registry() {
  const r = JSON.parse(fs.readFileSync(path.join(ROOT, 'governance/source-registry.json'), 'utf8'));
  return new Map(r.sources.map(s => [s.key, s]));
}

/** Source keys a wrapper actually names, in first-appearance order. */
function keysNamedBy(md, reg) {
  const seen = [];
  for (const m of md.matchAll(/`([a-z][a-z0-9_]{3,})`/g)) {
    const k = m[1];
    if (reg.has(k) && !seen.includes(k)) seen.push(k);
  }
  return seen;
}

function block(keys, reg) {
  const rows = keys.map(k => {
    const s = reg.get(k);
    const version = s.version_pin ? `v${s.version_pin}` : 'UNPINNED';
    return `| \`${k}\` | \`${s.file_id}\` | ${s.authority} | ${version} |`;
  });
  return [
    START,
    '',
    '**Controlling source pins.** Mirrored from `governance/source-registry.json`; parity enforced by',
    'T-34. Resolve **by `file_id`**, never by title. A pin is a pointer, not content — the live Drive',
    'document always wins, and a pin that disagrees with it is `REGISTRY DRIFT` (CLAUDE.md §4.3).',
    '',
    '| key | file_id | authority | registry version pin |',
    '|---|---|---|---|',
    ...rows,
    '',
    'If a filesystem read tool is available, also read the registry and report `PIN MATCHES LIVE` or',
    '`REGISTRY DRIFT`. **If it is not available, resolve from the pins above and state in the run report',
    'that no pin-versus-registry comparison was performed.** Never substitute a title search.',
    '',
    END,
  ].join('\n');
}

function agentFiles() {
  const dir = path.join(ROOT, '.claude/agents');
  return fs.readdirSync(dir).filter(f => f.endsWith('.md')).map(f => path.join(dir, f));
}

function run({ check }) {
  const reg = registry();
  let stale = 0, written = 0;
  for (const file of agentFiles()) {
    const md = fs.readFileSync(file, 'utf8');
    const body = md.includes(START) ? md.slice(0, md.indexOf(START)) + md.slice(md.indexOf(END) + END.length) : md;
    const keys = keysNamedBy(body, reg);
    if (keys.length === 0) continue;
    const want = block(keys, reg);

    const has = md.includes(START) && md.includes(END);
    const current = has ? md.slice(md.indexOf(START), md.indexOf(END) + END.length) : null;
    if (current === want) continue;

    if (check) {
      stale++;
      console.error(`STALE  ${path.relative(ROOT, file)}`);
      continue;
    }
    let next;
    if (has) {
      next = md.slice(0, md.indexOf(START)) + want + md.slice(md.indexOf(END) + END.length);
    } else {
      // Insert after the frontmatter block.
      const fm = md.match(/^---\n[\s\S]*?\n---\n/);
      const at = fm ? fm[0].length : 0;
      next = md.slice(0, at) + '\n' + want + '\n' + md.slice(at);
    }
    fs.writeFileSync(file, next);
    written++;
    console.log(`WROTE  ${path.relative(ROOT, file)}  (${keys.length} pins)`);
  }
  if (check) {
    console.log(stale === 0 ? 'all source-pin blocks current' : `${stale} stale block(s)`);
    process.exit(stale === 0 ? 0 : 1);
  }
  console.log(`${written} wrapper(s) updated`);
}

run({ check: process.argv.includes('--check') });
